/*
 * The channel between this app and the site it shows, over Chrome's postMessage for Trusted Web
 * Activities (Chrome 115 and later): https://developer.chrome.com/docs/android/post-message-twa
 *
 * Each time a page of the site finishes loading, the app asks Chrome for a message channel to
 * it; once it's ready, the app says hello, with what it can do, and the page (main-site/js/
 * app-bridge.js) answers on the port that came with it. Requests and their answers are JSON,
 * matched by an "id":
 *
 *   app -> page   {"type":"hello","app":"org.uwuapps.sgbus","version":"1.2.0","features":["calendar","update"]}
 *   page -> app   {"id":3,"type":"calendar","days":14}
 *   app -> page   {"id":3,"type":"calendar","events":[{"key","title","location","start","allDay"}]}
 *                 or {"id":3,"type":"calendar","error":"permission"} until the calendar is allowed
 *
 * Chrome checks the site lists this app with the "use_as_origin" relation in its
 * .well-known/assetlinks.json, so the page sees messages as coming from its own origin.
 *
 * Not generated by Bubblewrap: kept by `bubblewrap update` (see android/README.md).
 */
package org.uwuapps.sgbus;

import android.content.Context;
import android.net.Uri;
import android.os.Bundle;
import android.util.Log;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;
import androidx.browser.customtabs.CustomTabsCallback;
import androidx.browser.customtabs.CustomTabsService;
import androidx.browser.customtabs.CustomTabsSession;

import com.google.androidbrowserhelper.trusted.QualityEnforcer;
import com.google.androidbrowserhelper.trusted.TwaLauncher;

import org.json.JSONException;
import org.json.JSONObject;

import java.lang.reflect.Field;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;

final class AppBridge {
    private static final String TAG = "SgBusAppBridge";
    static final Uri ORIGIN = Uri.parse("https://sgbus.uwuapps.org");

    // The launcher of the TWA on screen, whose session the channel goes over.
    private static TwaLauncher sLauncher;
    private static final ExecutorService WORK = Executors.newSingleThreadExecutor();

    private AppBridge() {}

    static synchronized void adopt(TwaLauncher launcher) {
        sLauncher = launcher;
    }

    // TwaLauncher keeps its session to itself, so it's read from its field. Pinned to the
    // android-browser-helper version in app/build.gradle (2.5.0), and kept from R8's renaming by
    // proguard-rules.pro. Null if that ever changes: the page then just never hears from the app.
    @Nullable
    private static synchronized CustomTabsSession session() {
        if (sLauncher == null) return null;
        try {
            Field field = TwaLauncher.class.getDeclaredField("mSession");
            field.setAccessible(true);
            return (CustomTabsSession) field.get(sLauncher);
        } catch (ReflectiveOperationException | ClassCastException e) {
            Log.w(TAG, "No TWA session to message the page with", e);
            return null;
        }
    }

    static CustomTabsCallback callback(Context context) {
        return new Callback(context.getApplicationContext());
    }

    private static void post(JSONObject message) {
        CustomTabsSession session = session();
        if (session == null) return;
        int result = session.postMessage(message.toString(), null);
        if (result != CustomTabsService.RESULT_SUCCESS) Log.d(TAG, "postMessage: " + result);
    }

    // QualityEnforcer is Bubblewrap's usual callback; it carries on doing its job alongside this.
    private static final class Callback extends QualityEnforcer {
        private final Context mContext;

        Callback(Context context) {
            mContext = context;
        }

        @Override
        public void onNavigationEvent(int navigationEvent, @Nullable Bundle extras) {
            super.onNavigationEvent(navigationEvent, extras);
            if (navigationEvent != NAVIGATION_FINISHED) return;
            CustomTabsSession session = session();
            if (session == null) return;
            // A new page needs a channel of its own; Chrome checks the site vouches for this app.
            boolean asked = session.requestPostMessageChannel(ORIGIN, ORIGIN, new Bundle());
            Log.d(TAG, "Asked for a message channel: " + asked);
        }

        @Override
        public void onMessageChannelReady(@Nullable Bundle extras) {
            super.onMessageChannelReady(extras);
            try {
                String version = mContext.getPackageManager()
                        .getPackageInfo(mContext.getPackageName(), 0).versionName;
                JSONObject hello = new JSONObject()
                        .put("type", "hello")
                        .put("app", mContext.getPackageName())
                        .put("version", version)
                        // "update": it can update itself (UpdateActivity), from 1.2.0.
                        .put("features", new org.json.JSONArray().put("calendar").put("update"));
                post(hello);
            } catch (JSONException | android.content.pm.PackageManager.NameNotFoundException e) {
                Log.w(TAG, e);
            }
        }

        @Override
        public void onPostMessage(@NonNull String message, @Nullable Bundle extras) {
            super.onPostMessage(message, extras);
            WORK.execute(() -> answer(message));
        }

        private void answer(String message) {
            JSONObject request;
            try {
                request = new JSONObject(message);
            } catch (JSONException e) {
                return; // Not one of ours.
            }
            String type = request.optString("type");
            try {
                JSONObject reply = new JSONObject().put("id", request.opt("id")).put("type", type);
                if ("calendar".equals(type)) {
                    int days = Math.max(1, Math.min(31, request.optInt("days", 14)));
                    if (!CalendarReader.allowed(mContext)) reply.put("error", "permission");
                    else reply.put("events", CalendarReader.upcoming(mContext, days));
                } else {
                    reply.put("error", "unknown");
                }
                post(reply);
            } catch (JSONException | SecurityException e) {
                Log.w(TAG, e);
            }
        }
    }
}
